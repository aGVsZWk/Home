def main() -> int:
    if not SOURCE_ROOT.exists():
        print(f"Missing source directory: {SOURCE_ROOT}", file=sys.stderr)
        return 1
    out_dir = prepare_output_dir()
    files = discover_sources()
    targets = build_targets(files, out_dir)
    records: list[dict] = []
    errors: list[dict] = []

    for index, src in enumerate(files, start=1):
        rel_source = src.relative_to(SOURCE_ROOT).as_posix()
        out_file = targets[src]
        rel_markdown = out_file.relative_to(out_dir).as_posix()
        try:
            result = convert_file(src, out_file)
            record = {
                "source": rel_source,
                "markdown": rel_markdown,
                "title": src.stem,
                "status": result.get("status", "ok"),
                **{k: v for k, v in result.items() if k != "status"},
            }
            records.append(record)
            print(f"[{index}/{len(files)}] ok {rel_source}")
        except Exception as exc:  # Keep the batch going; report failures in the wiki.
            errors.append({"source": rel_source, "error": str(exc)})
            print(f"[{index}/{len(files)}] fail {rel_source}: {exc}", file=sys.stderr)

    make_dir_indexes(out_dir, records)
    make_root_indexes(out_dir, records, errors)
    print(f"Generated {len(records)} markdown pages in {out_dir}")
    if errors:
        print(f"{len(errors)} files failed; see 转换报告.md", file=sys.stderr)
        return 2
    return 0


