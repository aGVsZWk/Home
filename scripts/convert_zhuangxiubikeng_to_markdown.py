def printable_ratio(text: str) -> float:
    if not text:
        return 0.0
    good = sum(1 for ch in text if ch.isprintable() and not ch.isspace())
    return good / max(len(text), 1)


def looks_like_human_text(text: str) -> bool:
    stripped = text.strip()
    if len(stripped) < 2:
        return False
    bad = 0
    signal = 0
    for ch in stripped:
        if ch.isspace():
            continue
        if "\u4e00" <= ch <= "\u9fff":
            signal += 1
            continue
        if ch.isascii() and ch.isprintable():
            if ch.isalnum():
                signal += 1
            continue
        if "\uff00" <= ch <= "\uffef" or ch in COMMON_NON_ASCII:
            signal += 1
            continue
        bad += 1
    if signal < 2:
        return False
    return bad / max(len(stripped), 1) <= 0.12


def is_binary_allowed_char(ch: str) -> bool:
    return (
        "\u4e00" <= ch <= "\u9fff"
        or (ch.isascii() and ch.isprintable())
        or "\uff00" <= ch <= "\uffef"
        or ch in COMMON_NON_ASCII
        or ch.isspace()
    )


def binary_chunk_score(text: str) -> int:
    score = len(re.findall(r"[\u4e00-\u9fff]", text))
    score += 8 * len(XLS_SIGNAL_RE.findall(text))
    score -= sum(1 for ch in text if not is_binary_allowed_char(ch))
    return score


def normalize_binary_chunk(chunk: str) -> str:
    parts = [part.strip() for part in re.split(r"[Ā\x00]+", chunk) if part.strip()]
    if parts:
        chunk = max(parts, key=binary_chunk_score)
    chunk = re.sub(r"\s+", " ", chunk).strip()
    chunk = re.sub(r"^[^\u4e00-\u9fffA-Za-z0-9￥（【《]+", "", chunk)
    return chunk


def extract_binary_strings(src: Path) -> list[str]:
    data = src.read_bytes()
    candidates: list[str] = []
    for encoding in ("utf-16le", "gb18030", "utf-8"):
        decoded = data.decode(encoding, errors="ignore")
        if printable_ratio(decoded) < 0.02:
            continue
        chunks = re.split(r"[\x00-\x08\x0b\x0c\x0e-\x1f]+", decoded)
        for chunk in chunks:
            chunk = normalize_binary_chunk(chunk)
            if len(chunk) < 4:
                continue
            if not looks_like_human_text(chunk):
                continue
            has_signal = re.search(r"[\u4e00-\u9fffA-Za-z0-9]", chunk)
            if not has_signal:
                continue
            if not XLS_SIGNAL_RE.search(chunk):
                continue
            if len(chunk) > 240:
                chunk = chunk[:240].rstrip() + "..."
            candidates.append(chunk)

    seen: set[str] = set()
    cleaned: list[str] = []
    noise = {"Root Entry", "Workbook", "SummaryInformation", "DocumentSummaryInformation"}
    for item in candidates:
        if item in seen or item in noise:
            continue
        if item.startswith("_") and len(item) < 8:
            continue
        seen.add(item)
        cleaned.append(item)
        if len(cleaned) >= 240:
            break
    return cleaned


def convert_xls(src: Path, out_file: Path) -> dict:
    strings = extract_binary_strings(src)
    body = page_header(src.stem, src, "XLS")
    body += (
        "> 这是旧版 Excel 二进制文件，当前环境没有可靠的旧版表格解析器；"
        "下面是从文件中提取出的可读文本片段，表格结构可能不完整。\n\n"
    )
    if strings:
        body += "\n".join(f"- {item}" for item in strings)
        status = {"status": "partial", "method": "binary-string-extract", "items": len(strings)}
    else:
        body += "> 未提取到可读文本。\n"
        status = {"status": "partial", "method": "binary-string-extract", "items": 0}
    write_page(out_file, body)
    return status


def convert_copy_only(src: Path, out_file: Path) -> dict:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    asset = out_file.parent / f"{safe_filename_stem(src.stem)}{src.suffix.lower()}"
    shutil.copy2(src, asset)
    body = (
        page_header(src.stem, src, src.suffix.lower().lstrip(".").upper())
        + f"这个文件不是文本类资料，已复制为附件：[{src.name}]({md_link(asset.relative_to(out_file.parent))})\n"
    )
    write_page(out_file, body)
    return {"status": "partial", "method": "copy-attachment"}


def convert_file(src: Path, out_file: Path) -> dict:
    ext = src.suffix.lower()
    if ext in MARKDOWN_EXTS:
        return convert_markdown(src, out_file)
    if ext in DOCX_EXTS:
        return convert_docx(src, out_file)
    if ext in DOC_EXTS:
        return convert_doc(src, out_file)
    if ext in PDF_EXTS:
        return convert_pdf(src, out_file)
    if ext in XLSX_EXTS:
        return convert_xlsx(src, out_file)
    if ext in XLS_EXTS:
        return convert_xls(src, out_file)
    if ext in IMAGE_EXTS:
        return convert_image(src, out_file)
    if ext in COPY_ONLY_EXTS:
        return convert_copy_only(src, out_file)
    raise RuntimeError(f"Unsupported file type: {ext}")


def make_dir_indexes(out_dir: Path, records: list[dict]) -> None:
    pages_by_dir: dict[Path, list[dict]] = defaultdict(list)
    dirs: set[Path] = {Path(".")}
    for record in records:
        rel_page = Path(record["markdown"])
        pages_by_dir[rel_page.parent].append(record)
        current = rel_page.parent
        while current != Path("."):
            dirs.add(current)
            current = current.parent
    for directory in sorted(dirs, key=lambda p: (len(p.parts), p.as_posix())):
        if directory == Path("."):
            continue
        parent = out_dir / directory
        parent.mkdir(parents=True, exist_ok=True)
        child_dirs = sorted(
            [
                d
                for d in dirs
                if d.parent == directory and d != directory and d != BIKENG_MANUAL_SPLIT_DIR
            ],
            key=lambda p: p.name,
        )
        pages = sorted(pages_by_dir.get(directory, []), key=lambda r: r["title"])
        title = directory.name
        lines = [f"# {title}", "", f"[返回上一级]({md_link(Path('..') / 'README.md')})", ""]
        if child_dirs:
            lines.extend(["## 子目录", ""])
            for child in child_dirs:
                lines.append(f"- [{child.name}]({md_link(Path(child.name) / 'README.md')})")
            lines.append("")
        if pages:
            lines.extend(["## 文件", ""])
            for page in pages:
                link = Path(page["markdown"]).name
                lines.append(f"- [{page['title']}]({md_link(link)})")
            lines.append("")
        write_page(parent / "README.md", "\n".join(lines))


