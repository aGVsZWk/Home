def sha8(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:8]


def md_link(path: Path | str) -> str:
    return quote(Path(path).as_posix(), safe="/#%")


def summary_link(path: Path | str) -> str:
    return Path(path).as_posix()


def wrap_angle(path: Path | str) -> str:
    return f"<{Path(path).as_posix()}>"


def relative_link(target: Path, from_dir: Path) -> Path:
    return Path(os.path.relpath(target, from_dir))


def markdown_internal_href(path: Path | str) -> str:
    return wrap_angle(path)


def safe_filename_stem(name: str) -> str:
    stem = re.sub(r'[\\/:*?"<>|]', "-", name.strip())
    stem = re.sub(r"[()\[\]{}]", "-", stem)
    stem = re.sub(r"\s+", "-", stem)
    stem = re.sub(r"-+", "-", stem).strip("-. ")
    return stem or "untitled"


def clean_text(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%d %H:%M")
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, time):
        return value.strftime("%H:%M:%S")
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    text = str(value)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


def escape_honkit_templates(text: str) -> str:
    return text.replace("{", "&#123;").replace("}", "&#125;")


def table_cell(value: object) -> str:
    text = clean_text(value)
    text = text.replace("\\", "\\\\")
    text = text.replace("|", "\\|")
    text = text.replace("\n", "<br>")
    return text


def has_content(value: object) -> bool:
    return clean_text(value) != ""


def page_header(title: str, source: Path, kind: str) -> str:
    rel = source.relative_to(SOURCE_ROOT).as_posix()
    return (
        f"# {title}\n\n"
        f"> 来源：`{rel}`  \n"
        f"> 原格式：{kind}\n\n"
    )


def should_skip(path: Path) -> bool:
    if path.name in SKIP_NAMES:
        return True
    if path.name.startswith("~$"):
        return True
    parts = set(path.parts)
    return ".git" in parts or DEFAULT_OUT.name in parts


def discover_sources() -> list[Path]:
    files: list[Path] = []
    for path in SOURCE_ROOT.rglob("*"):
        if path.is_file() and not should_skip(path):
            files.append(path)
    return sorted(files, key=lambda p: p.relative_to(SOURCE_ROOT).as_posix())


def prepare_output_dir() -> Path:
    out_dir = DEFAULT_OUT
    if out_dir.exists():
        if (out_dir / MARKER).exists():
            shutil.rmtree(out_dir)
        else:
            stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
            out_dir = SOURCE_ROOT / f"wiki-markdown-{stamp}"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / MARKER).write_text(
        "Generated by scripts/convert_zhuangxiubikeng_to_markdown.py\n",
        encoding="utf-8",
    )
    return out_dir


def build_targets(files: Iterable[Path], out_dir: Path) -> dict[Path, Path]:
    used: set[Path] = set()
    targets: dict[Path, Path] = {}
    for src in files:
        rel = src.relative_to(SOURCE_ROOT)
        parent = out_dir / rel.parent
        stem = safe_filename_stem(src.stem)
        if src.suffix.lower() in MARKDOWN_EXTS and rel.name.lower() == "readme.md":
            stem = "原始README"
        candidate = parent / f"{stem}.md"
        if candidate.relative_to(out_dir) in used:
            candidate = parent / f"{stem}-{src.suffix.lower().lstrip('.')}.md"
        counter = 2
        while candidate.relative_to(out_dir) in used:
            candidate = parent / f"{stem}-{src.suffix.lower().lstrip('.')}-{counter}.md"
            counter += 1
        used.add(candidate.relative_to(out_dir))
        targets[src] = candidate
    return targets


def write_page(out_file: Path, content: str) -> None:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(escape_honkit_templates(content).rstrip() + "\n", encoding="utf-8")


def convert_markdown(src: Path, out_file: Path) -> dict:
    text = src.read_text(encoding="utf-8", errors="replace")
    write_page(out_file, page_header(src.stem, src, "Markdown") + text)
    return {"status": "ok"}


def convert_image(src: Path, out_file: Path) -> dict:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    asset = out_file.parent / f"{safe_filename_stem(src.stem)}{src.suffix.lower()}"
    if asset.exists() and asset.resolve() != src.resolve():
        asset = out_file.parent / f"{src.stem}-{sha8(src.as_posix())}{src.suffix}"
    shutil.copy2(src, asset)

    details = ""
    try:
        with Image.open(asset) as img:
            details = f"\n\n图片尺寸：{img.width} x {img.height}\n"
    except Exception:
        details = ""

    rel_asset = asset.relative_to(out_file.parent)
    body = (
        page_header(src.stem, src, src.suffix.lower().lstrip(".").upper())
        + f"![{src.stem}]({wrap_angle(rel_asset)})"
        + details
    )
    write_page(out_file, body)
    return {"status": "ok", "asset": asset.name}


def fallback_docx(src: Path) -> str:
    doc = Document(str(src))
    parts: list[str] = []
    for para in doc.paragraphs:
        text = clean_text(para.text)
        if text:
            parts.append(text)
    for table in doc.tables:
        rows: list[list[str]] = []
        for row in table.rows:
            rows.append([table_cell(cell.text) for cell in row.cells])
        parts.append(markdown_table(rows))
    return "\n\n".join(part for part in parts if part.strip())


def convert_docx(src: Path, out_file: Path) -> dict:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    asset_dir = f"assets_{sha8(src.relative_to(SOURCE_ROOT).as_posix())}"
    result = subprocess.run(
        [
            "pandoc",
            str(src),
            "-f",
            "docx",
            "-t",
            "gfm",
            "--wrap=none",
            f"--extract-media={asset_dir}",
            "-o",
            out_file.name,
        ],
        cwd=out_file.parent,
        capture_output=True,
        text=True,
        timeout=240,
    )
    if result.returncode == 0:
        body = out_file.read_text(encoding="utf-8", errors="replace")
        write_page(out_file, page_header(src.stem, src, "DOCX") + body)
        return {"status": "ok", "method": "pandoc"}

    body = fallback_docx(src)
    write_page(
        out_file,
        page_header(src.stem, src, "DOCX")
        + body
        + "\n\n> 注：Pandoc 转换失败，已用 Word 文本/表格提取方式兜底。\n",
    )
    return {"status": "ok", "method": "python-docx", "warning": result.stderr.strip()}


def convert_doc(src: Path, out_file: Path) -> dict:
    html = subprocess.run(
        ["textutil", "-convert", "html", "-stdout", str(src)],
        capture_output=True,
        timeout=180,
    )
    if html.returncode == 0 and html.stdout.strip():
        pandoc = subprocess.run(
            ["pandoc", "-f", "html", "-t", "gfm", "--wrap=none"],
            input=html.stdout,
            capture_output=True,
            timeout=180,
        )
        if pandoc.returncode == 0 and pandoc.stdout.strip():
            body = pandoc.stdout.decode("utf-8", errors="replace")
            write_page(out_file, page_header(src.stem, src, "DOC") + body)
            return {"status": "ok", "method": "textutil+pandoc"}

    txt = subprocess.run(
        ["textutil", "-convert", "txt", "-stdout", str(src)],
        capture_output=True,
        timeout=180,
    )
    if txt.returncode == 0 and txt.stdout.strip():
        body = txt.stdout.decode("utf-8", errors="replace")
        write_page(out_file, page_header(src.stem, src, "DOC") + body)
        return {"status": "ok", "method": "textutil"}

    raise RuntimeError((txt.stderr or html.stderr).decode("utf-8", errors="replace"))


def pdf_page_markdown(text: str) -> str:
    pages = text.replace("\r", "").split("\f")
    parts: list[str] = []
    for index, page in enumerate(pages, start=1):
        lines = [line.rstrip() for line in page.splitlines()]
        while lines and not lines[0].strip():
            lines.pop(0)
        while lines and not lines[-1].strip():
            lines.pop()
        if not lines:
            continue
        rendered = "\n".join((line + "  ") if line.strip() else "" for line in lines)
        parts.append(f"## 第 {index} 页\n\n{rendered}")
    return "\n\n".join(parts)


def render_pdf_pages_from_file(
    pdf_file: Path,
    out_file: Path,
    asset_key: str,
    *,
    dpi: int = 180,
) -> tuple[Path, list[Path]]:
    asset_dir = out_file.parent / f"assets_{sha8(asset_key)}" / "pdf-pages"
    asset_dir.mkdir(parents=True, exist_ok=True)
    prefix = asset_dir / "page"
    result = subprocess.run(
        ["pdftoppm", "-jpeg", "-r", str(dpi), str(pdf_file), str(prefix)],
        capture_output=True,
        text=True,
        timeout=600,
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or "pdftoppm failed")
    pages = sorted(asset_dir.glob("page-*.jpg"), key=lambda p: p.name)
    return asset_dir, pages


def render_pdf_pages(src: Path, out_file: Path) -> tuple[Path, list[Path]]:
    return render_pdf_pages_from_file(
        src,
        out_file,
        src.relative_to(SOURCE_ROOT).as_posix(),
    )


def crop_image_whitespace(image_file: Path, *, padding: int = 36, threshold: int = 245) -> None:
    with Image.open(image_file) as image:
        rgb = image.convert("RGB")
        gray = rgb.convert("L")
        mask = gray.point(lambda pixel: 255 if pixel < threshold else 0, "1")
        bbox = mask.getbbox()
        if not bbox:
            return

        left, top, right, bottom = bbox
        left = max(0, left - padding)
        top = max(0, top - padding)
        right = min(rgb.width, right + padding)
        bottom = min(rgb.height, bottom + padding)

        if (left, top, right, bottom) == (0, 0, rgb.width, rgb.height):
            return
        rgb.crop((left, top, right, bottom)).save(image_file, quality=92, optimize=True)


def crop_pdf_page_whitespace(page_images: Iterable[Path]) -> None:
    for image in page_images:
        crop_image_whitespace(image)


def crop_image_to_table_grid(image_file: Path, *, padding: int = 18, threshold: int = 235) -> None:
    with Image.open(image_file) as image:
        gray = image.convert("L")
        width, height = gray.size
        pixels = gray.load()

        column_counts = []
        for x in range(width):
            count = 0
            for y in range(height):
                if pixels[x, y] < threshold:
                    count += 1
            column_counts.append(count)

        row_counts = []
        for y in range(height):
            count = 0
            for x in range(width):
                if pixels[x, y] < threshold:
                    count += 1
            row_counts.append(count)

        table_columns = [x for x, count in enumerate(column_counts) if count > height * 0.15]
        table_rows = [y for y, count in enumerate(row_counts) if count > width * 0.25]
        if not table_columns or not table_rows:
            return

        left = max(0, min(table_columns) - padding)
        right = min(width, max(table_columns) + padding)
        top = max(0, min(table_rows) - padding)
        bottom = min(height, max(table_rows) + padding)
        if right - left < width * 0.25 or bottom - top < height * 0.25:
            return

        image.convert("RGB").crop((left, top, right, bottom)).save(
            image_file,
            quality=92,
            optimize=True,
        )


def crop_flow_sheet_images(page_images: Iterable[Path]) -> None:
    for image in page_images:
        crop_image_whitespace(image)
        crop_image_to_table_grid(image)


def page_span(start: int, end: int) -> str:
    return f"手册第 {start} 页" if start == end else f"手册第 {start}-{end} 页"


def toc_entry_has_children(index: int) -> bool:
    level = BIKENG_MANUAL_TOC[index][0]
    for next_level, _, _ in BIKENG_MANUAL_TOC[index + 1 :]:
        if next_level <= level:
            return False
        return True
    return False


def toc_entry_end(index: int, max_manual_page: int, children: bool) -> int:
    level, _, start = BIKENG_MANUAL_TOC[index]
    for next_level, _, next_start in BIKENG_MANUAL_TOC[index + 1 :]:
        if next_start <= start:
            continue
        if children and next_level <= level:
            return next_start - 1
        if not children:
            return next_start - 1
    return max_manual_page


def honkit_anchor(text: str) -> str:
    anchor = text.strip().lower()
    anchor = re.sub(r"\s+", "-", anchor)
    anchor = re.sub(r"[^\w\u4e00-\u9fff\-（）()]+", "", anchor)
    return anchor


def manual_heading_text(index: int, max_manual_page: int) -> str:
    _, title, start = BIKENG_MANUAL_TOC[index]
    end = toc_entry_end(index, max_manual_page, toc_entry_has_children(index))
    return f"{title}（{page_span(start, end)}）"


def manual_page_rel(index: int) -> Path:
    _, title, start = BIKENG_MANUAL_TOC[index]
    return BIKENG_MANUAL_SPLIT_DIR / f"{start:02d}-{safe_filename_stem(title)}.md"


def manual_summary_lines(path_prefix: Path = Path("."), indent: int = 0) -> list[str]:
    max_manual_page = 98
    manual_path = path_prefix / BIKENG_MANUAL_MD
    lines = [f"{'    ' * indent}* [装修避坑手册打印（100页）]({summary_link(manual_path)})"]
    for index, (level, title, _) in enumerate(BIKENG_MANUAL_TOC):
        page_path = path_prefix / manual_page_rel(index)
        child_indent = indent + level - 1
        lines.append(f"{'    ' * child_indent}* [{title}]({summary_link(page_path)})")
    return lines


def pdf_page_image_line(page_images: list[Path], out_file: Path, pdf_page: int, alt: str) -> str:
    if pdf_page < 1 or pdf_page > len(page_images):
        return f"> 缺少 PDF 第 {pdf_page} 页图片。"
    rel_image = relative_link(page_images[pdf_page - 1], out_file.parent)
    return f"![{alt}]({wrap_angle(rel_image)})"


def child_toc_indexes(index: int) -> list[int]:
    level = BIKENG_MANUAL_TOC[index][0]
    children: list[int] = []
    for child_index, (child_level, _, _) in enumerate(BIKENG_MANUAL_TOC[index + 1 :], start=index + 1):
        if child_level <= level:
            break
        if child_level == level + 1:
            children.append(child_index)
    return children


def convert_bikeng_manual_pdf(src: Path, out_file: Path, original_pdf: Path, page_images: list[Path]) -> dict:
    max_manual_page = max(len(page_images) - 2, 0)
    split_dir = out_file.parent / BIKENG_MANUAL_SPLIT_DIR.name
    split_dir.mkdir(parents=True, exist_ok=True)
    pdf_link = f"[打开原始 PDF]({md_link(original_pdf.relative_to(out_file.parent))})"
    lines = [
        page_header(src.stem, src, "PDF"),
        f"> {pdf_link}",
        "",
        "这个入口页只放目录，具体页面图片已经拆到下面每个章节页面，避免打开时一次加载 100 页图片。",
        "",
        "## 原 PDF",
        "",
        f"- {pdf_link}",
        "",
        "## 目录",
        "",
    ]
    for index, (level, title, _) in enumerate(BIKENG_MANUAL_TOC):
        indent = "  " * (level - 2)
        rel_page = manual_page_rel(index).relative_to(BIKENG_MANUAL_MD.parent)
        lines.append(
            f"{indent}- [{manual_heading_text(index, max_manual_page)}]({markdown_internal_href(rel_page)})"
        )
    write_page(out_file, "\n".join(lines))

    for index, (level, title, start) in enumerate(BIKENG_MANUAL_TOC):
        has_children = toc_entry_has_children(index)
        end = toc_entry_end(index, max_manual_page, has_children)
        page_path = out_file.parent / manual_page_rel(index).relative_to(BIKENG_MANUAL_MD.parent)
        child_lines = [
            f"# {manual_heading_text(index, max_manual_page)}",
            "",
            f"[返回目录]({markdown_internal_href(Path('..') / BIKENG_MANUAL_MD.name)})",
            "",
            f"> [打开原始 PDF]({md_link(relative_link(original_pdf, page_path.parent))})",
            "",
        ]
        children = child_toc_indexes(index)
        if children:
            child_lines.extend(["## 子目录", ""])
            for child_index in children:
                child_lines.append(
                    f"- [{manual_heading_text(child_index, max_manual_page)}]"
                    f"({markdown_internal_href(manual_page_rel(child_index).name)})"
                )
            child_lines.append("")
        else:
            for manual_page in range(start, end + 1):
                pdf_page = manual_page + 2
                child_lines.append(
                    pdf_page_image_line(
                        page_images,
                        page_path,
                        pdf_page,
                        title,
                    )
                )
                child_lines.append("")
        write_page(page_path, "\n".join(child_lines))

    return {
        "status": "ok",
        "method": "pdftoppm+manual-toc-split-pages",
        "pages": len(page_images),
        "split_pages": len(BIKENG_MANUAL_TOC),
    }


def convert_pdf(src: Path, out_file: Path) -> dict:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    original_pdf = out_file.parent / f"{safe_filename_stem(src.stem)}.pdf"
    if original_pdf.exists() and original_pdf.resolve() != src.resolve():
        original_pdf = out_file.parent / f"{safe_filename_stem(src.stem)}-{sha8(src.as_posix())}.pdf"
    shutil.copy2(src, original_pdf)

    result = subprocess.run(
        ["pdftotext", "-layout", "-enc", "UTF-8", str(src), "-"],
        capture_output=True,
        timeout=420,
    )
    text = result.stdout.decode("utf-8", errors="replace") if result.stdout else ""
    text_body = pdf_page_markdown(text)
    try:
        _, page_images = render_pdf_pages(src, out_file)
    except Exception as exc:
        page_images = []
        render_warning = str(exc)
    else:
        render_warning = ""

    if src.relative_to(SOURCE_ROOT) == BIKENG_MANUAL_REL and page_images:
        return convert_bikeng_manual_pdf(src, out_file, original_pdf, page_images)

    image_body = []
    for index, image in enumerate(page_images, start=1):
        rel_image = image.relative_to(out_file.parent)
        image_body.append(f"![{src.stem}]({wrap_angle(rel_image)})")

    pdf_link = f"[打开原始 PDF]({md_link(original_pdf.relative_to(out_file.parent))})"
    body_parts = [f"> {pdf_link}\n"]
    if image_body:
        body_parts.extend(image_body)
    elif render_warning:
        body_parts.append(f"> PDF 页面图片渲染失败：{render_warning}\n")

    if text_body.strip():
        body_parts.extend(["## 可复制文字", text_body])
        status = {"status": "ok", "method": "pdftotext+pdftoppm", "pages": len(page_images)}
    else:
        status = {
            "status": "ok" if page_images else "partial",
            "method": "pdftoppm",
            "pages": len(page_images),
            "warning": "no text extracted",
        }
        if not page_images:
            body_parts.append("> 这个 PDF 未提取到可复制文字，可能是扫描图或图片型 PDF。")
    write_page(out_file, page_header(src.stem, src, "PDF") + "\n\n".join(body_parts))
    return status


